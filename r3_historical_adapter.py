def parse_dt(s):
    x = datetime.fromisoformat(s.replace("Z","+00:00"))
    if x.tzinfo is None:
        raise ValueError("timestamps must be timezone-aware")
    return x.astimezone(timezone.utc)


def pct(a,b):
    return (float(a)/float(b)-1.0)*100.0 if b else 0.0


def directional(side,value):
    return float(value) if side == "LONG" else -float(value)


def ema(values,period):
    vals=[float(x) for x in values]
    if len(vals)<period:
        return None
    alpha=2.0/(period+1.0)
    e=sum(vals[:period])/period
    for x in vals[period:]:
        e=alpha*x+(1-alpha)*e
    return e


def rsi(values,period=14):
    vals=[float(x) for x in values]
    if len(vals)<period+1:
        return None
    gains=[]; losses=[]
    for a,b in zip(vals[-(period+1):-1],vals[-period:]):
        d=b-a
        gains.append(max(d,0.0)); losses.append(max(-d,0.0))
    ag=sum(gains)/period; al=sum(losses)/period
    if al == 0:
        return 100.0 if ag>0 else 50.0
    rs=ag/al
    return 100.0-100.0/(1.0+rs)


def volume_ratio(values,lookback=20):
    if len(values)<lookback+1:
        return 0.0
    prev=[float(x) for x in values[-(lookback+1):-1]]
    avg=sum(prev)/len(prev) if prev else 0.0
    return float(values[-1])/avg if avg>0 else 0.0


def aligned(side,price,fast,slow):
    if side=="LONG":
        return price>fast>slow
    return price<fast<slow


def trend_label(price,fast,slow):
    if price>fast>slow:
        return "UP"
    if price<fast<slow:
        return "DOWN"
    return "MIXED"


def read_candles(path, interval_minutes):
    by=defaultdict(list)
    with open(path,newline="",encoding="utf-8-sig") as f:
        for r in csv.DictReader(f):
            t=parse_dt(r["timestamp"])
            item={
                "t":t,
                "end":t+timedelta(minutes=interval_minutes),
                "symbol":r["symbol"].upper(),
                "open":float(r["open"]),
                "high":float(r["high"]),
                "low":float(r["low"]),
                "close":float(r["close"]),
                "volume":float(r.get("volume") or 0),
                "quote_volume":float(r.get("quote_volume") or 0),
            }
            if min(item["open"],item["high"],item["low"],item["close"])<=0:
                continue
            by[item["symbol"]].append(item)
    for s in by:
        by[s].sort(key=lambda x:x["t"])
    return by


def completed(series, scan_t, n=None):
    ends=[x["end"] for x in series]
    idx=bisect.bisect_right(ends,scan_t)
    if n is None:
        return series[:idx]
    return series[max(0,idx-n):idx]


def latest_completed(series, scan_t):
    x=completed(series,scan_t,1)
    return x[-1] if x else None


def rolling_quote_24h(c1_by, symbol, scan_t):
    rows=completed(c1_by.get(symbol,[]),scan_t)
    if not rows:
        return 0.0
    cutoff=scan_t-timedelta(hours=24)
    return sum(x["quote_volume"] for x in rows if x["end"]>cutoff)


def price_24h_ago(c1_by,symbol,scan_t):
    rows=c1_by.get(symbol,[])
    if not rows:
        return None
    target=scan_t-timedelta(hours=24)
    ends=[x["end"] for x in rows]
    idx=bisect.bisect_right(ends,target)-1
    return rows[idx]["close"] if idx>=0 else None


def ticker_proxy(c1_by,symbol,scan_t,spread_pct):
    last=latest_completed(c1_by.get(symbol,[]),scan_t)
    if not last:
        return None
    p=last["close"]
    half=spread_pct/200.0
    return {
        "last":p,
        "bid":p*(1-half),
        "ask":p*(1+half),
        "spread_pct":spread_pct,
        "quote_volume":rolling_quote_24h(c1_by,symbol,scan_t),
        "change_24h":pct(p,price_24h_ago(c1_by,symbol,scan_t) or p),
    }


def market_context(c15_by,c1h_by,scan_t):
    bull=bear=0
    details={}
    for symbol in ("BTC-USDT","ETH-USDT"):
        symbol_info={}
        for label,src in (("15m",c15_by),("1h",c1h_by)):
            bars=completed(src.get(symbol,[]),scan_t,80)
            closes=[x["close"] for x in bars]
            if len(closes)<55:
                state="UNKNOWN"
            else:
                e20,e50=ema(closes,20),ema(closes,50)
                p=closes[-1]
                if p>e20>e50:
                    state="UP"; bull+=1
                elif p<e20<e50:
                    state="DOWN"; bear+=1
                else:
                    state="MIXED"
            symbol_info[label]=state
        details[symbol]=symbol_info
    return {"bull":bull,"bear":bear,"details":details}


def market_alignment_for(side,ctx):
    return int(ctx["bull"] if side=="LONG" else ctx["bear"])


def analyze_setup(symbol,side,radar_move,live_price,scan_t,c5_by,c15_by,c1h_by,ctx):
    c5=completed(c5_by.get(symbol,[]),scan_t,100)
    c15=completed(c15_by.get(symbol,[]),scan_t,100)
    c1h=completed(c1h_by.get(symbol,[]),scan_t,90)
    if min(len(c5),len(c15),len(c1h))<55:
        return None

    close5=[x["close"] for x in c5]
    close15=[x["close"] for x in c15]
    close1h=[x["close"] for x in c1h]
    high5=[x["high"] for x in c5]
    low5=[x["low"] for x in c5]
    vol5=[x["volume"] for x in c5]

    p5,p15,p1h=close5[-1],close15[-1],close1h[-1]
    e9_5,e20_5=ema(close5,9),ema(close5,20)
    e20_15,e50_15=ema(close15,20),ema(close15,50)
    e20_1h,e50_1h=ema(close1h,20),ema(close1h,50)
    rsi5=rsi(close5,14)
    if any(x is None for x in (e9_5,e20_5,e20_15,e50_15,e20_1h,e50_1h,rsi5)):
        return None

    prev_high=max(high5[-21:-1])
    prev_low=min(low5[-21:-1])
    reference=prev_high if side=="LONG" else prev_low
    breakout=p5>prev_high if side=="LONG" else p5<prev_low

    align5=aligned(side,p5,e9_5,e20_5)
    align15=aligned(side,p15,e20_15,e50_15)
    align1h=aligned(side,p1h,e20_1h,e50_1h)

    mom5=pct(close5[-1],close5[-4])
    dmom5=directional(side,mom5)
    vr5=volume_ratio(vol5)
    ext5=directional(side,pct(p5,e20_5))
    market_align=market_alignment_for(side,ctx)

    passed=sum([
        int(breakout),int(align5),int(align15),int(align1h),
        int(market_align>=MIN_MARKET_ALIGNMENT),
        int(vr5>=MIN_5M_VOLUME_RATIO),
        int(dmom5>=MIN_5M_DIRECTIONAL_MOM),
        int(ext5<=MAX_5M_EXTENSION),
    ])
    strength=passed/8.0*100.0

    decision="WATCH"; reason="breakout setup passed; wait for pullback"
    if not breakout:
        decision,reason="REJECT_NO_BREAKOUT","5m close has not broken prior 20-bar structure"
    elif not align5 or not align15:
        decision,reason="REJECT_STRUCTURE","5m/15m structure not aligned"
    elif market_align<MIN_MARKET_ALIGNMENT:
        decision,reason="REJECT_MARKET",f"BTC/ETH alignment {market_align} < {MIN_MARKET_ALIGNMENT}"
    elif vr5<MIN_5M_VOLUME_RATIO:
        decision,reason="REJECT_VOLUME",f"5m volume ratio {vr5:.2f} < {MIN_5M_VOLUME_RATIO:.2f}"
    elif dmom5<MIN_5M_DIRECTIONAL_MOM:
        decision,reason="REJECT_MOMENTUM",f"5m directional momentum {dmom5:.2f}% too weak"
    elif ext5>MAX_5M_EXTENSION:
        decision,reason="REJECT_EXTENSION",f"5m extension {ext5:.2f}% > {MAX_5M_EXTENSION:.2f}%"
    elif side=="LONG" and rsi5>LONG_MAX_RSI5:
        decision,reason="REJECT_RSI",f"LONG RSI5 {rsi5:.1f} > {LONG_MAX_RSI5:.1f}"
    elif side=="SHORT" and rsi5<SHORT_MIN_RSI5:
        decision,reason="REJECT_RSI",f"SHORT RSI5 {rsi5:.1f} < {SHORT_MIN_RSI5:.1f}"

    # R3.1 timing patch: if completed 5m did not break, but live proxy did,
    # carry it as PENDING_BREAKOUT.
    if decision=="REJECT_NO_BREAKOUT":
        live_crossed=live_price>reference if side=="LONG" else live_price<reference
        if live_crossed:
            decision="PENDING_BREAKOUT"
            reason="live Radar price crossed prior 20-bar structure; wait for completed 5m close"

    return {
        "symbol":symbol,"side":side,"decision":decision,"reason":reason,
        "radar_move_pct":radar_move,"setup_price":live_price,
        "reference_level":reference,"setup_strength":strength,
        "market_alignment":market_align,"rsi_5m":rsi5,
        "volume_ratio_5m":vr5,"directional_momentum_5m":dmom5,
        "extension_5m":ext5,"align_5m":align5,"align_15m":align15,
        "align_1h":align1h,
        "trend_15m":trend_label(p15,e20_15,e50_15),
        "trend_1h":trend_label(p1h,e20_1h,e50_1h),
    }


def recheck_stored_breakout(x,stored_reference):
    # Mirror _recheck_after_stored_breakout in r3_job_v31.py.
    x=dict(x)
    market_align=int(x["market_alignment"])
    vr5=float(x["volume_ratio_5m"])
    dmom5=float(x["directional_momentum_5m"])
    ext5=float(x["extension_5m"])
    rsi5=float(x["rsi_5m"])
    align5=bool(x["align_5m"]); align15=bool(x["align_15m"]); align1h=bool(x["align_1h"])

    passed=1+int(align5)+int(align15)+int(align1h)
    passed+=int(market_align>=MIN_MARKET_ALIGNMENT)
    passed+=int(vr5>=MIN_5M_VOLUME_RATIO)
    passed+=int(dmom5>=MIN_5M_DIRECTIONAL_MOM)
    passed+=int(ext5<=MAX_5M_EXTENSION)
    x["setup_strength"]=passed/8.0*100.0
    x["reference_level"]=stored_reference

    decision="WATCH"; reason="stored Radar breakout confirmed by completed 5m close; wait for pullback"
    if not align5 or not align15:
        decision,reason="REJECT_STRUCTURE","5m/15m structure not aligned after breakout confirmation"
    elif market_align<MIN_MARKET_ALIGNMENT:
        decision,reason="REJECT_MARKET",f"BTC/ETH alignment {market_align} < {MIN_MARKET_ALIGNMENT}"
    elif vr5<MIN_5M_VOLUME_RATIO:
        decision,reason="REJECT_VOLUME",f"5m volume ratio {vr5:.2f} < {MIN_5M_VOLUME_RATIO:.2f}"
    elif dmom5<MIN_5M_DIRECTIONAL_MOM:
        decision,reason="REJECT_MOMENTUM",f"5m directional momentum {dmom5:.2f}% too weak"
    elif ext5>MAX_5M_EXTENSION:
        decision,reason="REJECT_EXTENSION",f"5m extension {ext5:.2f}% > {MAX_5M_EXTENSION:.2f}%"
    elif x["side"]=="LONG" and rsi5>LONG_MAX_RSI5:
        decision,reason="REJECT_RSI",f"LONG RSI5 {rsi5:.1f} > {LONG_MAX_RSI5:.1f}"
    elif x["side"]=="SHORT" and rsi5<SHORT_MIN_RSI5:
        decision,reason="REJECT_RSI",f"SHORT RSI5 {rsi5:.1f} < {SHORT_MIN_RSI5:.1f}"
    x["decision"]=decision; x["reason"]=reason
    return x


def local_trigger(c1_by,symbol,side,scan_t):
    bars=completed(c1_by.get(symbol,[]),scan_t,40)
    if len(bars)<25:
        return None
    closes=[x["close"] for x in bars]
    highs=[x["high"] for x in bars]
    lows=[x["low"] for x in bars]
    vols=[x["volume"] for x in bars]
    mom=directional(side,pct(closes[-1],closes[-4]))
    vr=volume_ratio(vols)
    level=max(highs[-4:-1]) if side=="LONG" else min(lows[-4:-1])
    return {"level":float(level),"mom":float(mom),"vr":float(vr)}


def recent_trigger_event(c1_by,symbol,side,trigger_level,scan_t):
    bars=completed(c1_by.get(symbol,[]),scan_t,60)
    if len(bars)<25:
        return None
    closes=[x["close"] for x in bars]
    vols=[x["volume"] for x in bars]
    start=max(20,len(bars)-max(TRIGGER_LOOKBACK_MIN,1))
    latest=None
    for i in range(start,len(bars)):
        close_i=closes[i]
        crossed=close_i>trigger_level if side=="LONG" else close_i<trigger_level
        if not crossed:
            continue
        j=max(0,i-3)
        mom=directional(side,pct(close_i,closes[j]))
        prev=vols[max(0,i-20):i]
        avg=sum(prev)/len(prev) if prev else 0.0
        vr=vols[i]/avg if avg>0 else 0.0
        latest={"level":trigger_level,"close":close_i,"mom":mom,"vr":vr,
                "bars_ago":len(bars)-1-i}
    return latest


def side_return(side,entry,x):
    return (entry-x)/entry*100.0 if side=="SHORT" else (x-entry)/entry*100.0


def level(entry,side,move):
    return entry*(1+move/100.0) if side=="LONG" else entry*(1-move/100.0)


def stop_hit(side,bar,target):
    return bar["high"]>=target if side=="SHORT" else bar["low"]<=target


def tp_hit(side,bar,target):
    return bar["low"]<=target if side=="SHORT" else bar["high"]>=target


def gross_stop(side,entry,tp1,tp2,h1,h2,stop):
    realized=0.0; remaining=1.0
    if h1:
        realized+=W1*side_return(side,entry,tp1); remaining-=W1
    if h2:
        realized+=W2*side_return(side,entry,tp2); remaining-=W2
    return realized+remaining*side_return(side,entry,stop)


def simulate_exit(side,entry,entry_time,bars):
    tp1=level(entry,side,TP1); tp2=level(entry,side,TP2); tp3=level(entry,side,TP3)
    sl=level(entry,side,-SL)
    h1=h2=h3=False
    last=None
    for bar in bars:
        if bar["end"]<=entry_time:
            continue
        last=bar
        age=(bar["end"]-entry_time).total_seconds()/3600.0
        if (not h1) and age>=4.0:
            gross=side_return(side,entry,bar["open"])
            net=gross-ROUND_TRIP_COST_PCT
            return bar["end"],bar["open"],"TIMEOUT_EXIT",gross,net,h1,h2,h3,True

        if h2:
            active=tp1; reason="TP2_PROTECT_EXIT"
        elif h1:
            active=entry; reason="BREAKEVEN_EXIT"
        else:
            active=sl; reason="SL_EXIT"

        if stop_hit(side,bar,active):
            gross=gross_stop(side,entry,tp1,tp2,h1,h2,active)
            net=gross-ROUND_TRIP_COST_PCT
            return bar["end"],active,reason,gross,net,h1,h2,h3,True

        if (not h1) and tp_hit(side,bar,tp1):
            h1=True
            if stop_hit(side,bar,entry):
                gross=gross_stop(side,entry,tp1,tp2,True,False,entry)
                net=gross-ROUND_TRIP_COST_PCT
                return bar["end"],entry,"BREAKEVEN_EXIT",gross,net,True,False,False,True

        if (not h2) and tp_hit(side,bar,tp2):
            h1=h2=True
            if stop_hit(side,bar,tp1):
                gross=gross_stop(side,entry,tp1,tp2,True,True,tp1)
                net=gross-ROUND_TRIP_COST_PCT
                return bar["end"],tp1,"TP2_PROTECT_EXIT",gross,net,True,True,False,True

        if (not h3) and tp_hit(side,bar,tp3):
            h1=h2=True
            if stop_hit(side,bar,tp1):
                gross=gross_stop(side,entry,tp1,tp2,True,True,tp1)
                net=gross-ROUND_TRIP_COST_PCT
                return bar["end"],tp1,"TP2_PROTECT_EXIT",gross,net,True,True,False,True
            gross=W1*TP1+W2*TP2+W3*TP3
            net=gross-ROUND_TRIP_COST_PCT
            return bar["end"],tp3,"TP3_EXIT",gross,net,True,True,True,True

    return None,(last["close"] if last else entry),"UNRESOLVED",0.0,0.0,h1,h2,h3,False


def risk_allows(scan_t,trades):
    closed=[x for x in trades if x["resolved"] and x["exit_time"] and x["exit_time"]<=scan_t]
    day_start=scan_t.replace(hour=0,minute=0,second=0,microsecond=0)
    daily=sum(x["sim_pnl_usdt"] for x in closed if x["exit_time"]>=day_start)
    if daily<=-abs(DAILY_MAX_LOSS_USDT):
        return False,"DAILY_LOSS_LIMIT"

    closed.sort(key=lambda x:x["exit_time"],reverse=True)
    streak=0; latest_loss=None
    for x in closed[:max(MAX_CONSECUTIVE_LOSSES,1)]:
        if x["net_return_pct"]<=0:
            streak+=1
            if latest_loss is None:
                latest_loss=x["exit_time"]
        else:
            break
    if streak>=MAX_CONSECUTIVE_LOSSES and latest_loss:
        if (scan_t-latest_loss).total_seconds()<PAUSE_HOURS_AFTER_STREAK*3600:
            return False,"LOSS_STREAK_PAUSE"
    return True,"OK"


def active_open_count(scan_t,trades):
    n=0
    for x in trades:
        if x["entry_time"]>scan_t:
            continue
        if not x["resolved"] or not x["exit_time"] or scan_t<x["exit_time"]:
            n+=1
    return n


def symbol_blocked(symbol,scan_t,trades):
    for x in trades:
        if x["symbol"]!=symbol or x["entry_time"]>scan_t:
            continue
        still_open=(not x["resolved"]) or (x["exit_time"] and scan_t<x["exit_time"])
        cooldown=scan_t < x["entry_time"]+timedelta(hours=COOLDOWN_HOURS)
        if still_open or cooldown:
            return True
    return False


